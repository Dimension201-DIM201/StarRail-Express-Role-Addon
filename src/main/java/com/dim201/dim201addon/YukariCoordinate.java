package com.dim201.dim201addon;

/**
 * 八云紫的坐标点
 */
public class YukariCoordinate {
    public double x, y, z;
    public String level;

    public YukariCoordinate(double x, double y, double z, String level) {
        this.x = x;
        this.y = y;
        this.z = z;
        this.level = level;
    }
}